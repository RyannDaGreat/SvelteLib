/**
 * NODE-FLOW core suite: the port type table, the coercion table, connection
 * resolution and refusal, cycle handling, graph evaluation, and the derive-side
 * geometry (port anchors, wires) that the canvas and the painter share.
 *
 * WHAT THIS FILE IS FOR THAT THE DOCTESTS ARE NOT. Every pure function in
 * core/nodeflow.js carries executable examples and tests/doctest_test.js runs them,
 * so the per-function contracts are already pinned. This suite pins the things that
 * are true of the SYSTEM rather than of any one function:
 *   - the trio actually computes 3 × 2 = 6 THROUGH THE REGISTERED PLUGINS, not
 *     through a fixture that merely looks like them;
 *   - a connection is ordinary keyframable state, so the same graph on two slides
 *     produces two different pictures and a tween between them retweens the value;
 *   - the app.css --a-port-* mirror actually matches the core color table;
 *   - derive injects nodePorts and only for node widgets (every other document
 *     stays byte-identical);
 *   - refusals: type mismatch, missing port, and cycles, each with a sentence.
 */

