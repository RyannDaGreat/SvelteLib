check("nodePortAnchors follows ROTATION and SCALE, so a rotated node's wires land on its beads", () => {
  // A QUARTER TURN about the item origin, at 2x. `world.rotation` is in RADIANS
  // (core/transform.js) — a fact worth pinning here, because the same anchors feed
  // the wire layer and the bead hit test, and a degrees/radians mix-up would put
  // every wire endpoint somewhere no bead can be grabbed.
  const world = { x: 0, y: 0, rotation: Math.PI / 2, scale: 2 };
  const node = { itemId: "m", world, state: { w: 100, h: 90 }, plugin: nodeMathPlugin };
  const out = nodePortAnchors(node).find((a) => a.key === "out");
  // local (100, 34) → scale 2 → (200, 68) → +90°: (x, y) ↦ (−y, x) → (−68, 200)
  assert.ok(Math.abs(out.x - -68) < 1e-9, `rotated output x: want -68, got ${out.x}`);
  assert.ok(Math.abs(out.y - 200) < 1e-9, `rotated output y: want 200, got ${out.y}`);
  // AND THE HIT TEST AGREES: inverting the same world puts the bead back at its
  // declared LOCAL position, which is the property that makes one geometry enough.
  const back = T.apply(T.invert(world), out.x, out.y);
  assert.ok(Math.abs(back.x - 100) < 1e-9 && Math.abs(back.y - 34) < 1e-9, "world→local round trip lands on the declared bead");
});

