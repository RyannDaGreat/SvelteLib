check("A PATCH MAY DIFFER PER SLIDE: the same items, rewired on slide 2", () => {
  // The whole reason connections live in ordinary state. Slide 0 wires src(3)→disp;
  // slide 1 rewires disp to read `two`(2) instead. Nothing in nodeflow.js knows
  // about slides — this works because a connection is a state leaf like any other.
  const doc = {
    meta: { slideW: 1280, slideH: 720 },
    slides: [
      { id: "s0", name: "one", delta: { items: {
        cam: { type: "camera", x: 0, y: 0, w: 1280, h: 720 },
        src: { type: "node_number", x: 0, y: 0, w: 130, h: 90, value: 3 },
        two: { type: "node_number", x: 0, y: 200, w: 130, h: 90, value: 2 },
        disp: { type: "node_display", x: 400, y: 0, w: 140, h: 90, inputs: { in: { item: "src", port: "out" } } },
      } } },
      { id: "s1", name: "two", delta: { items: { disp: { inputs: { in: { item: "two", port: "out" } } } } } },
    ],
  };
  const at = (i) => evaluateNodeGraph(evaluateState(foldState(doc, i, 1), registry).state.items, registry).values.disp.inputs.in;
  assert.strictEqual(at(0), 3, "slide 0 reads the source of 3");
  assert.strictEqual(at(1), 2, "slide 1 was REWIRED to the source of 2");
});

