// ── CYCLES ───────────────────────────────────────────────────────────────────

check("a cycle is REFUSED AT CONNECT TIME, with a sentence about the loop", () => {
  // disp is already downstream of src, so wiring disp back into src closes a loop.
  // disp has no outputs, so use mul→src, which is the same shape.
  const why = connectionRefusal(trio(), registry, { item: "mul", port: "out" }, { item: "src", port: "a" });
  // src has no inputs at all, so the port check fires first — that is the correct
  // precedence (a nonexistent port makes the cycle question meaningless). Prove
  // the cycle rule itself on a graph where both ports exist:
  assert.match(why, /no input named/);
  const items = trio({ mid: { type: "node_math", x: 0, y: 400, w: 150, h: 90, inputs: { a: { item: "mul", port: "out" } } } });
  assert.match(connectionRefusal(items, registry, { item: "mid", port: "out" }, { item: "mul", port: "a" }), /would make a loop/);
});

check("a self-connection is a cycle of length one and is caught by the same rule", () => {
  assert.ok(wouldCycle(trio(), registry, { item: "mul", port: "out" }, { item: "mul", port: "a" }));
});

check("a legal parallel path is NOT a cycle (a diamond is fine)", () => {
  const items = trio({ other: { type: "node_math", x: 0, y: 500, w: 150, h: 90, inputs: { a: { item: "src", port: "out" } } } });
  assert.ok(!wouldCycle(items, registry, { item: "other", port: "out" }, { item: "disp", port: "in" }),
    "src feeds both mul and other; joining them downstream is a diamond, not a loop");
});

check("a port declaring feedbackSafe is exempt from the cycle rule (the reserved audio escape)", () => {
  const reg = {
    get: () => ({ ports: () => ({ inputs: [{ key: "i", type: "audio" }, { key: "fb", type: "audio", feedbackSafe: true }], outputs: [{ key: "o", type: "audio" }] }) }),
  };
  const items = { a: { type: "n", inputs: { fb: { item: "b", port: "o" } } }, b: { type: "n" } };
  // b→a exists but enters a feedbackSafe port, so a→b does NOT close a loop.
  assert.ok(!wouldCycle(items, reg, { item: "a", port: "o" }, { item: "b", port: "i" }));
  // The same edge on an ORDINARY port does close one.
  const strict = { a: { type: "n", inputs: { i: { item: "b", port: "o" } } }, b: { type: "n" } };
  assert.ok(wouldCycle(strict, reg, { item: "a", port: "o" }, { item: "b", port: "i" }));
});

check("topoOrder survives a hand-edited cyclic document instead of hanging, and names the cycle", () => {
  const items = { a: { type: "x", inputs: { i: { item: "b", port: "o" } } }, b: { type: "x", inputs: { i: { item: "a", port: "o" } } } };
  const { order, cyclic } = topoOrder(items);
  assert.deepStrictEqual(order.slice().sort(), ["a", "b"], "every item still appears exactly once");
  assert.deepStrictEqual(cyclic.slice().sort(), ["a", "b"], "and the cycle is REPORTED, not swallowed");
});

