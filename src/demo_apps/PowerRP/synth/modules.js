/**
 * THE MODULE LIBRARY — the v1 module set, one factory each.
 *
 * COUNT: 23 modules, where the blueprint's MODULE SET v1 enumerates 22. The
 * extra one is `sampleHold`. It is not a deviation from intent: the blueprint's
 * IMPLEMENTATION LAW names "sample+hold" as one of the five required
 * AudioWorklet processors, but the module enumeration one paragraph later omits
 * it. Building the worklet and then not exposing a module for it would leave a
 * processor no patch could reach, so it is registered like the other 22. The
 * count is measured by tests/synth_engine_test.js, not asserted from here.
 *
 * ── THE UNIFORM SHAPE ────────────────────────────────────────────────────────
 * Every factory takes (context, params, resources) and returns:
 *
 *   {
 *     inputs:  { <portName>: AudioNode | AudioParam },   // where wires land
 *     outputs: { <portName>: AudioNode },                // where wires start
 *     params:  { <key>: AudioParam | setter },           // knobs
 *     start(): void,      // begin any oscillators (idempotent)
 *     dispose(): void,    // stop and release everything
 *     meta:    { kind, label, ... }
 *   }
 *
 * The engine NEVER special-cases a module type — it only ever looks up ports by
 * name and ramps gains around them. That uniformity is what makes glitch-free
 * rewiring one implementation rather than 22, and it is why adding a 23rd
 * module requires no engine change at all.
 *
 * ── NATIVE FIRST (blueprint, THE SYNTH ENGINE 2) ─────────────────────────────
 * 18 of the 23 modules are built ENTIRELY from native AudioNodes, which are C++
 * under the hood. Only 5 reach for an AudioWorklet, and each one's docstring
 * says which native node it would have used if one existed. The `IMPLEMENTATION`
 * constant below is the machine-readable version of that accounting, so the
 * claim is checkable rather than a comment that can rot.
 *
 * ── PARAM SETTERS AND WHY THEY ARE NOT ALL AudioParams ───────────────────────
 * Most knobs map to a real AudioParam, which gives sample-accurate ramping for
 * free. Some (an oscillator's waveform, a filter's type, a scale table) are
 * DISCRETE and have no AudioParam equivalent; those are exposed as plain setter
 * functions. The engine's setParam handles both, and `rampSeconds` is silently
 * meaningless for the discrete ones — documented per module rather than
 * pretending a waveform can crossfade.
 *
 * Zero PowerRP imports (the ENGINE law).
 */

