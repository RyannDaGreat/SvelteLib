// ─── 22. METALLIC DING (wow module) ──────────────────────────────────────────

/**
 * METALLIC DING — an FM bell, and one of the two modules the user asked to be
 * genuinely beautiful.
 *
 * ── WHY FM AND NOT SUBTRACTIVE ───────────────────────────────────────────────
 * A bell's overtones are INHARMONIC — not integer multiples of the fundamental.
 * Subtractive synthesis starts from a harmonic waveform and can only remove;
 * it can never produce inharmonic partials, which is why filtered saws sound
 * like organs and never like bells. FM generates inharmonic sidebands directly
 * from a non-integer carrier:modulator ratio, which is why it has been THE bell
 * technique since Chowning in 1973.
 *
 * ── WHAT MAKES IT SOUND REAL (the details that matter) ───────────────────────
 * 1. THE MODULATION INDEX DECAYS FASTER THAN THE AMPLITUDE. This is the single
 *    most important one. A real bell is BRIGHT at the strike and PURE as it
 *    rings out — the high partials die first. If the index held constant, the
 *    result is a buzzer with a volume envelope. dsp.bellVoice enforces
 *    indexDecaySeconds < ampDecaySeconds by construction.
 * 2. EXPONENTIAL, NOT LINEAR, DECAY. Struck resonant objects lose energy
 *    proportionally to what they have, which is exponential. A linear fade
 *    sounds like someone turning a knob down.
 * 3. A TOUCH OF INHARMONIC SHIMMER. A second, quieter carrier at a slightly
 *    offset ratio beats against the first, which is what gives real bells their
 *    slow "wobble" as they ring. Without it the tail is sterile.
 * 4. THE STRIKE TRANSIENT. A very short filtered noise burst at onset supplies
 *    the "clank" of hammer-on-metal that pure FM lacks. It is brief enough
 *    (~12 ms) to read as part of the attack rather than as noise.
 *
 * Native throughout — oscillators, gains and an envelope drawn with AudioParam
 * automation. Nothing here needs a worklet, because the envelope is scheduled
 * ONCE per strike rather than retriggered live.
 */
function dingModule(context, params, resources) {
  const output = context.createGain();
  const preset = params.preset ?? "ding";
  if (!BELL_PRESETS[preset]) {
    throw new Error(
      `Unknown bell preset ${JSON.stringify(preset)}; expected one of ${Object.keys(BELL_PRESETS).join(", ")}`,
    );
  }
  output.gain.value = clampParam(params.level ?? 0.5, 0, 1, "level");

  // ── THE PITCH SEAM (wave 3): a WIRE-CONNECTABLE frequency, sampled at STRIKE ──
  //
  // The knob's value lives on a ConstantSourceNode's offset rather than in a
  // plain JS number, and `frequency` is that offset — which is what makes it an
  // ordinary AudioParam any control signal can be connected INTO. Web Audio sums
  // every connection into a param, so a sequencer's pitch output patched here
  // ADDS to the knob; the knob therefore reads as an OFFSET (set it to 0 and the
  // wire alone determines the pitch, set it to 220 and the wire transposes up
  // from there), which is the modular convention and the one that makes an
  // unpatched ding behave exactly as it did before this existed.
  //
  // ── WHY SAMPLED AT TRIGGER TIME AND NOT AUDIO-RATE ──────────────────────────
  // A struck bell is not a running oscillator being retuned: `trigger` builds a
  // fresh FM voice per strike (see below), and that voice's carrier/modulator
  // ratio is FIXED at construction because a bell's inharmonic partials are a
  // property of the object that was struck. Continuously sweeping a ringing
  // bell's pitch is not what a bell does — it is what a siren does. So the port
  // sets THE PITCH OF THE NEXT STRIKE, read here as `pitchBus.offset.value`.
  //
  // Reading `.value` is exact for this use and NOT an approximation of an
  // audio-rate read: `.value` returns the param's current computed value
  // including every connected input's contribution, and a strike is a single
  // instant, so there is nothing to average over. The one honest limitation is
  // that a source scheduled to change at a FUTURE time (a sequencer's
  // setValueAtTime for the next step) is not visible yet — which is exactly
  // right, because the strike being scheduled belongs to the step whose pitch is
  // current. This is why per-strike voice semantics are PRESERVED rather than
  // worked around.
  //
  // ── THE OFFSET IS NOT CLAMPED TO THE AUDIBLE BAND, AND THAT IS THE POINT ────
  // Every other frequency in this file is clamped to [MIN_AUDIBLE_HZ, …] at
  // construction, because it IS a pitch and a sub-audio pitch is an authoring
  // mistake worth catching. This one is an OFFSET that a wire sums into, and its
  // most useful value is ZERO — "the wire alone names the note", which is what a
  // sequenced melody wants. Clamping it to 20 Hz would silently detune every
  // note in that patch by 20 Hz and there would be nothing to see. What IS still
  // checked is finiteness (clampParam's own first job), across a range that
  // permits a negative offset — transposing DOWN is a legitimate patch.
  // The strike itself is clamped to the audible band, where it is a real pitch.
  const pitchBus = createConstant(context, clampParam(params.frequency ?? 880, -MAX_AUDIBLE_HZ, MAX_AUDIBLE_HZ, "frequency"));
  pitchBus.start();

  return {
    inputs: { level: output.gain, frequency: pitchBus.offset },
    outputs: { out: output },
    params: {
      level: output.gain,
      frequency: pitchBus.offset,
    },
    /**
     * Command. Strike the bell at an audio-clock time. Builds a fresh voice per
     * strike and disposes it on ended — bells are one-shot, so a persistent
     * voice would be wasted CPU between strikes, and per-strike voices give
     * free polyphony (overlapping rings).
     *
     * `options.frequency` (what engine.trigger passes through) still WINS over
     * the port, because it is a caller naming a pitch for one specific strike —
     * a patch's random-pitched gull — and that is more specific than a standing
     * wire. With neither, the knob's own offset is the pitch.
     */
    trigger(time = context.currentTime, options = {}) {
      // Out-of-range is CLAMPED rather than refused: unlike a knob (whose value
      // the author typed and whose mistake is worth a sentence), this number can
      // be the sum of a wire and an offset, and a modulation that briefly
      // overshoots must not throw on the audio path and kill the strike.
      const struckAt = options.frequency ?? Math.max(MIN_AUDIBLE_HZ, Math.min(MAX_AUDIBLE_HZ, pitchBus.offset.value));
      const voice = bellVoice(preset, struckAt);
      const carrier = context.createOscillator();
      const modulator = context.createOscillator();
      const modulationDepth = context.createGain();
      const amplitude = context.createGain();
      const shimmer = context.createOscillator();
      const shimmerGain = context.createGain();

      carrier.frequency.value = voice.carrierHz;
      modulator.frequency.value = voice.modulatorHz;

      // FM: the modulator's output, scaled to Hz, is ADDED to the carrier's
      // frequency. That addition is what Web Audio's param connection does.
      modulationDepth.gain.setValueAtTime(voice.modulationDepthHz, time);
      modulationDepth.gain.exponentialRampToValueAtTime(
        voice.modulationDepthHz * INDEX_FLOOR_FRACTION,
        time + voice.indexDecaySeconds,
      );
      modulator.connect(modulationDepth);
      modulationDepth.connect(carrier.frequency);

      // Detail 3: the shimmer partial, slightly off-ratio so it beats.
      shimmer.frequency.value = voice.carrierHz * SHIMMER_RATIO;
      shimmerGain.gain.value = SHIMMER_LEVEL;
      shimmer.connect(shimmerGain);
      shimmerGain.connect(amplitude);

      // Detail 2: exponential amplitude decay after a very fast attack.
      amplitude.gain.setValueAtTime(0, time);
      amplitude.gain.linearRampToValueAtTime(1, time + BELL_ATTACK_SECONDS);
      amplitude.gain.exponentialRampToValueAtTime(SILENCE_FLOOR, time + voice.ampDecaySeconds);

      carrier.connect(amplitude);
      amplitude.connect(output);

      // Detail 4: the strike transient.
      const strike = context.createBufferSource();
      const strikeFilter = context.createBiquadFilter();
      const strikeGain = context.createGain();
      strike.buffer = resources.strikeNoise();
      strikeFilter.type = "bandpass";
      strikeFilter.frequency.value = voice.carrierHz * STRIKE_BAND_RATIO;
      strikeFilter.Q.value = STRIKE_Q;
      strikeGain.gain.setValueAtTime(STRIKE_LEVEL, time);
      strikeGain.gain.exponentialRampToValueAtTime(SILENCE_FLOOR, time + STRIKE_SECONDS);
      strike.connect(strikeFilter);
      strikeFilter.connect(strikeGain);
      strikeGain.connect(output);

      const stopTime = time + voice.ampDecaySeconds + VOICE_TAIL_PADDING;
      for (const node of [carrier, modulator, shimmer, strike]) {
        node.start(time);
        node.stop(stopTime);
      }
      carrier.onended = () => {
        for (const node of [carrier, modulator, shimmer, strike, modulationDepth, amplitude, shimmerGain, strikeFilter, strikeGain]) {
          node.disconnect();
        }
      };
    },
    start() {},
    dispose() {
      // The pitch bus is a STARTED source, so it must be stopped as well as
      // disconnected — a running ConstantSourceNode keeps its whole graph alive
      // and the engine's leak check counts it.
      pitchBus.stop();
      pitchBus.disconnect();
      output.disconnect();
    },
    meta: { kind: "ding", label: "Metallic Ding", preset },
  };
}

/** exponentialRampToValueAtTime cannot reach 0 (it is undefined there), so
 * every decay targets this instead — 100 dB down, inaudible. */
const SILENCE_FLOOR = 0.0001;

/** The index decays TO this fraction of its peak, not to nothing: a bell's tail
 * keeps a little inharmonic content, and ramping to true silence sounds like
 * the timbre is being switched off. */
const INDEX_FLOOR_FRACTION = 0.02;

const BELL_ATTACK_SECONDS = 0.002;

/** Slightly sharp of a perfect fifth — deliberately NOT a simple ratio, so it
 * beats slowly against the carrier instead of locking into consonance. */
const SHIMMER_RATIO = 2.53;
const SHIMMER_LEVEL = 0.12;

const STRIKE_SECONDS = 0.012;
const STRIKE_LEVEL = 0.35;
const STRIKE_BAND_RATIO = 3.2;
const STRIKE_Q = 1.4;

/** Extra time before stopping a voice, so the exponential tail is not cut. */
const VOICE_TAIL_PADDING = 0.2;

// ─── 23. AMBIENCE PAD (wow module) ───────────────────────────────────────────

/**
 * AMBIENCE PAD — an entire spacey synth as ONE module, spacey by default.
 *
 * The user asked for "a module that's just an entire synth", and for the result
 * to sound like "whooshing around in space". This is that module: patch nothing
 * else, connect it to the output, and it is already the sound.
 *
 * ── THE SIGNAL CHAIN AND WHY EACH STAGE IS THERE ─────────────────────────────
 *   supersaw stack        — 7 detuned saws. The detuning beats at ~0.3-1 Hz,
 *                           which is the "alive, breathing" quality; a single
 *                           saw sounds thin and static no matter what follows.
 *   + sub sine            — one octave down, quiet. Supplies weight the saw
 *                           stack lacks; felt more than heard.
 *   -> lowpass filter     — tames the saws' harsh upper harmonics. Pads live
 *                           BEHIND things, and unfiltered saws fight the
 *                           foreground.
 *   <- slow LFO on cutoff — 0.06 Hz, ±700 Hz. THE motion. Slow enough to never
 *                           read as an effect, just as "the sound is moving".
 *                           This is the single most important stage for
 *                           avoiding listener fatigue over a long presentation.
 *   -> shimmer delay      — a long, heavily damped, ping-pong delay. Smears the
 *                           pad into a wash and widens it across the stereo
 *                           field.
 *   -> deep-space reverb  — the generated IR with a slow bloom. Puts it in a
 *                           very large room.
 *
 * Every stage is a native AudioNode. The whole module is ~14 nodes, which is
 * nothing — the browser runs them in C++.
 */
function padModule(context, params, resources) {
  const output = context.createGain();
  const voiceMix = context.createGain();
  const filter = context.createBiquadFilter();
  const lfo = context.createOscillator();
  const lfoDepth = context.createGain();
  const subOscillator = context.createOscillator();
  const subGain = context.createGain();

  const rootFrequency = clampParam(params.frequency ?? 82.4, MIN_AUDIBLE_HZ, MAX_AUDIBLE_HZ, "frequency");
  const detunes = supersawDetunes(params.voices ?? PAD_VOICES, params.spread ?? PAD_SPREAD_CENTS);

  output.gain.value = clampParam(params.level ?? 0.34, 0, 1, "level");
  voiceMix.gain.value = 1 / Math.sqrt(detunes.length);

  const oscillators = detunes.map((cents) => {
    const oscillator = context.createOscillator();
    oscillator.type = "sawtooth";
    oscillator.frequency.value = rootFrequency;
    oscillator.detune.value = cents;
    oscillator.connect(voiceMix);
    return oscillator;
  });

  subOscillator.type = "sine";
  subOscillator.frequency.value = rootFrequency / 2;
  subGain.gain.value = PAD_SUB_LEVEL;
  subOscillator.connect(subGain);
  subGain.connect(voiceMix);

  filter.type = "lowpass";
  filter.frequency.value = clampParam(params.cutoff ?? PAD_CUTOFF_HZ, MIN_AUDIBLE_HZ, MAX_AUDIBLE_HZ, "cutoff");
  filter.Q.value = PAD_RESONANCE;

  lfo.type = "sine";
  lfo.frequency.value = clampParam(params.motion ?? PAD_LFO_HZ, MIN_LFO_HZ, MAX_LFO_HZ, "motion");
  lfoDepth.gain.value = PAD_LFO_DEPTH_HZ;
  lfo.connect(lfoDepth);
  lfoDepth.connect(filter.frequency);

  voiceMix.connect(filter);

  // The shimmer delay and reverb, built inline from the same primitives the
  // standalone modules use (NOT by importing them — a module composing another
  // module would be the plugin-imports-plugin mistake in a different file).
  const delayLeft = context.createDelay(MAX_DELAY_SECONDS);
  const delayRight = context.createDelay(MAX_DELAY_SECONDS);
  const delayFeedback = context.createGain();
  const delayDamping = context.createBiquadFilter();
  const delayMerger = context.createChannelMerger(2);
  const delayWet = context.createGain();

  delayLeft.delayTime.value = PAD_DELAY_SECONDS;
  delayRight.delayTime.value = PAD_DELAY_SECONDS * PAD_DELAY_SKEW;
  delayFeedback.gain.value = PAD_DELAY_FEEDBACK;
  delayDamping.type = "lowpass";
  delayDamping.frequency.value = PAD_DELAY_DAMPING_HZ;
  delayWet.gain.value = PAD_DELAY_WET;

  filter.connect(delayLeft);
  delayLeft.connect(delayRight);
  delayRight.connect(delayDamping);
  delayDamping.connect(delayFeedback);
  delayFeedback.connect(delayLeft);
  delayLeft.connect(delayMerger, 0, 0);
  delayRight.connect(delayMerger, 0, 1);
  delayMerger.connect(delayWet);

  const convolver = context.createConvolver();
  const reverbWet = context.createGain();
  convolver.normalize = true;
  convolver.buffer = resources.impulseResponse(params.space ?? "deepSpace");
  reverbWet.gain.value = clampParam(params.reverb ?? PAD_REVERB_WET, 0, 1, "reverb");

  filter.connect(output); // dry
  delayWet.connect(output);
  delayWet.connect(convolver);
  filter.connect(convolver);
  convolver.connect(reverbWet);
  reverbWet.connect(output);

  let started = false;
  return {
    inputs: { level: output.gain, cutoff: filter.frequency },
    outputs: { out: output },
    params: {
      level: output.gain,
      cutoff: filter.frequency,
      motion: lfo.frequency,
      reverb: reverbWet.gain,
      frequency: (value, when, ramp) => {
        const target = clampParam(value, MIN_AUDIBLE_HZ, MAX_AUDIBLE_HZ, "frequency");
        for (const oscillator of oscillators) {
          if (ramp > 0) oscillator.frequency.setTargetAtTime(target, when, ramp);
          else oscillator.frequency.setValueAtTime(target, when);
        }
        if (ramp > 0) subOscillator.frequency.setTargetAtTime(target / 2, when, ramp);
        else subOscillator.frequency.setValueAtTime(target / 2, when);
      },
    },
    start() {
      if (started) return;
      for (const oscillator of oscillators) oscillator.start();
      subOscillator.start();
      lfo.start();
      started = true;
    },
    dispose() {
      for (const oscillator of oscillators) {
        if (started) oscillator.stop();
        oscillator.disconnect();
      }
      if (started) {
        subOscillator.stop();
        lfo.stop();
      }
      for (const node of [
        voiceMix, filter, lfo, lfoDepth, subOscillator, subGain, delayLeft, delayRight,
        delayFeedback, delayDamping, delayMerger, delayWet, convolver, reverbWet, output,
      ]) {
        node.disconnect();
      }
    },
    meta: { kind: "pad", label: "Ambience Pad" },
  };
}

// ─── 24. POLY PAD (the polyphonic voice pool) ────────────────────────────────

/**
 * POLY PAD — N independent voices with one shared tone-shaping chain, played by
 * note events rather than by a frequency knob.
 *
 * ── WHY THIS IS A NEW MODULE AND NOT A FLAG ON THE PAD ──────────────────────
 * "Polyphonic demos are important" (user, 2026-08-03). The obvious move is to
 * teach `padModule` to be polyphonic, and it is the wrong one for a stated
 * reason: the pad is a DRONE. Its whole interface is one `frequency` knob and a
 * sound that is always on, and every patch in both libraries relies on that —
 * SPACEY_PAD_DRONE connects it to an output and nothing else, and it plays. A
 * poly pad has no sound at rest and no frequency knob at all; it has a pitch
 * INPUT and a gate. Those are different modules that happen to share a timbre,
 * and merging them would mean a `poly: true` knob that silently changes what
 * every other knob on the card means.
 *
 * THE SEAM THIS ESTABLISHES, and it is the part meant to outlive this module: a
 * poly module is one that exposes `noteOn(note, frequency, time)` and
 * `noteOff(note, time)` alongside the ordinary instance shape. The ENGINE
 * dispatches to those (see engine.noteOn/noteOff) and nothing else in the engine
 * changes — MONO MODULES ARE UNTOUCHED, they simply do not declare the methods
 * and the engine says so loudly if you send them a note. That is the same
 * discipline `trigger` already follows.
 *
 * ── VOICES ARE BUILT EAGERLY, WHICH IS A REAL TRADE ─────────────────────────
 * All N voices exist from construction: oscillators started, gains at zero. The
 * alternative is building a voice per note-on, which is what dingModule does and
 * is right there — a bell is a one-shot whose voice dies on its own. A pad voice
 * is HELD, so per-note construction would allocate several AudioNodes inside the
 * note-on handler, i.e. on the gesture path, and connect them while sound is
 * playing. Eager voices cost CPU that is not being heard, which is why the count
 * is a knob with a ceiling (synth/voices.MAX_POLY_VOICES) rather than unbounded.
 *
 * ── THE ALLOCATION DECISION IS NOT HERE ─────────────────────────────────────
 * Which slot a note lands on, and which note gets stolen, is synth/voices.js —
 * pure, and tested in bare node. This module owns only the AudioNodes: given a
 * slot index, retune it and open its envelope. Keeping the two apart is what
 * makes "the 9th note steals the oldest" an ordinary assertion instead of
 * something you have to hear.
 */
function polyPadModule(context, params) {
  const output = context.createGain();
  const filter = context.createBiquadFilter();
  const lfo = context.createOscillator();
  const lfoDepth = context.createGain();

  const voiceCount = Math.floor(clampParam(params.voices ?? DEFAULT_POLY_VOICES, MIN_POLY_VOICES, MAX_POLY_VOICES, "voices"));
  const detunes = supersawDetunes(POLY_DETUNE_COUNT, params.spread ?? POLY_SPREAD_CENTS);

  output.gain.value = clampParam(params.level ?? 0.3, 0, 1, "level");

  filter.type = "lowpass";
  filter.frequency.value = clampParam(params.cutoff ?? POLY_CUTOFF_HZ, MIN_AUDIBLE_HZ, MAX_AUDIBLE_HZ, "cutoff");
  filter.Q.value = POLY_RESONANCE;
  filter.connect(output);

  // The shared slow filter sweep — one LFO for the whole instrument, not one per
  // voice: a pad's motion is a property of the patch, and N independent sweeps
  // beating against each other is a chorus, not a pad.
  lfo.type = "sine";
  lfo.frequency.value = clampParam(params.motion ?? POLY_LFO_HZ, 0.01, 20, "motion");
  lfoDepth.gain.value = POLY_LFO_DEPTH_HZ;
  lfo.connect(lfoDepth);
  lfoDepth.connect(filter.frequency);

  /**
   * One voice: a small detuned saw stack through its own envelope gain.
   *
   * The envelope is an ordinary AudioParam ramp rather than the ADSR worklet,
   * deliberately: this module must work before `init()` has loaded the worklets
   * (a poly pad in a deck that loads mid-presentation), and attack/release on a
   * gain is exactly what a pad envelope is. The worklet ADSR remains the module
   * you patch when you want a shaped envelope on something else.
   */
  const voices = Array.from({ length: voiceCount }, () => {
    const gain = context.createGain();
    gain.gain.value = 0;
    const oscillators = detunes.map((cents) => {
      const oscillator = context.createOscillator();
      oscillator.type = "sawtooth";
      oscillator.frequency.value = POLY_REST_HZ;
      oscillator.detune.value = cents;
      oscillator.connect(gain);
      return oscillator;
    });
    gain.connect(filter);
    return { gain, oscillators };
  });

  // ── THE PITCH SEAM, AND WHY IT IS A ConstantSourceNode ──────────────────────
  // Identical in shape and in reasoning to dingModule's: `pitch` is the OFFSET of
  // a ConstantSourceNode, which makes it an ordinary AudioParam that any control
  // signal can be wired INTO and that Web Audio SUMS. So a keyboard's pitch
  // output and a transpose knob add up with no scaling module in between.
  //
  // It is SAMPLED AT NOTE-ON, not audio-rate, and that is the same ruling the
  // ding made for the same reason: a held chord whose voices all glide when the
  // pitch input moves is a siren, not a chord. The note being started belongs to
  // the pitch that is current when the key goes down.
  //
  // A caller MAY still name a frequency per note (engine.noteOn's third
  // argument, which is what a keyboard does — it knows exactly which key was
  // pressed). That WINS over the port, exactly as options.frequency wins for a
  // ding: naming a pitch for one specific note is more specific than a standing
  // wire. The port is for the patch that drives pitch by a wire alone.
  const pitchBus = createConstant(context, clampParam(params.pitch ?? POLY_REST_HZ, -MAX_AUDIBLE_HZ, MAX_AUDIBLE_HZ, "pitch"));
  pitchBus.start();

  const attack = () => clampParam(params.attack ?? POLY_ATTACK_SECONDS, 0.001, 4, "attack");
  const release = () => clampParam(params.release ?? POLY_RELEASE_SECONDS, 0.01, 8, "release");
  // Each voice carries 1/sqrt(N) of full scale so a held chord does not clip
  // where a single note did not — the same power-summing convention the supersaw
  // uses for its own stack.
  const voiceLevel = 1 / Math.sqrt(voiceCount);

  let started = false;
  return {
    inputs: { level: output.gain, cutoff: filter.frequency, pitch: pitchBus.offset },
    outputs: { out: output },
    params: {
      level: output.gain,
      cutoff: filter.frequency,
      motion: lfo.frequency,
      pitch: pitchBus.offset,
    },
    /**
     * Command. Sound `frequency` on voice `slot` at an audio-clock time.
     *
     * The pitch is set with `setValueAtTime` rather than ramped: a stolen voice
     * gliding from the note it was playing to the new one is a portamento
     * nobody asked for, and it is exactly what makes voice stealing audible.
     * The AMPLITUDE does ramp (the attack), which is what covers the switch.
     *
     * Args:
     *     slot (number): which voice, from synth/voices.js
     *     frequency (number): the note in Hz
     *     time (number): audio-clock time
     */
    noteOn(slot, frequency, time = context.currentTime) {
      const voice = voices[slot];
      if (!voice) throw new RangeError(`poly pad has ${voices.length} voices; no slot ${slot}`);
      // The caller's frequency wins; with none, the pitch PORT names the note.
      // Clamped rather than refused on this path: the value can be the sum of a
      // wire and an offset, and a modulation that briefly overshoots must not
      // throw on the audio path and kill the note.
      const named = frequency ?? pitchBus.offset.value;
      const hz = Math.max(MIN_AUDIBLE_HZ, Math.min(MAX_AUDIBLE_HZ, named));
      for (const oscillator of voice.oscillators) oscillator.frequency.setValueAtTime(hz, time);
      voice.gain.gain.cancelScheduledValues(time);
      // Anchor at the CURRENT value before ramping. Without this, a voice
      // stolen mid-release would jump to wherever its last scheduled ramp had
      // reached rather than continuing from where it audibly is — a click.
      voice.gain.gain.setValueAtTime(voice.gain.gain.value, time);
      voice.gain.gain.linearRampToValueAtTime(voiceLevel, time + attack());
    },
    /** Command. Release voice `slot`. Ramps to zero over the release time. */
    noteOff(slot, time = context.currentTime) {
      const voice = voices[slot];
      if (!voice) throw new RangeError(`poly pad has ${voices.length} voices; no slot ${slot}`);
      voice.gain.gain.cancelScheduledValues(time);
      voice.gain.gain.setValueAtTime(voice.gain.gain.value, time);
      voice.gain.gain.linearRampToValueAtTime(0, time + release());
    },
    start() {
      if (started) return;
      for (const voice of voices) for (const oscillator of voice.oscillators) oscillator.start();
      lfo.start();
      started = true;
    },
    dispose() {
      for (const voice of voices) {
        for (const oscillator of voice.oscillators) {
          if (started) oscillator.stop();
          oscillator.disconnect();
        }
        voice.gain.disconnect();
      }
      if (started) lfo.stop();
      // The pitch bus is a started source like any other; the engine's leak
      // check counts it, so it must be stopped as well as disconnected.
      pitchBus.stop();
      pitchBus.disconnect();
      for (const node of [filter, lfo, lfoDepth, output]) node.disconnect();
    },
    meta: { kind: "polyPad", label: "Poly Pad", voices: voiceCount },
  };
}

/** How many detuned saws make up ONE poly voice. Three, not the supersaw's
 *  seven: a poly pad may have eight voices sounding at once, and 56 oscillators
 *  is a real cost for a thickness nobody can hear inside a chord. */
const POLY_DETUNE_COUNT = 3;
const POLY_SPREAD_CENTS = 11;
const POLY_CUTOFF_HZ = 1400;
const POLY_RESONANCE = 1.2;
/** Slower than the mono pad's sweep — a chord already moves. */
const POLY_LFO_HZ = 0.09;
const POLY_LFO_DEPTH_HZ = 500;
/** Where a silent voice's oscillators park. Any audible frequency will do (they
 *  are at zero gain); a real one avoids a denormal-adjacent value. */
const POLY_REST_HZ = 220;
/** A pad's envelope: slow enough to swell, fast enough that a played chord
 *  arrives with the gesture rather than after it. */
const POLY_ATTACK_SECONDS = 0.12;
const POLY_RELEASE_SECONDS = 0.45;

/** Pad voicing constants — the "spacey by default" settings. */
const PAD_VOICES = 7;
const PAD_SPREAD_CENTS = 16;
const PAD_SUB_LEVEL = 0.3;
const PAD_CUTOFF_HZ = 900;
const PAD_RESONANCE = 3.5;

/** 0.06 Hz = one full sweep every ~16 s. Slow enough to read as "the sound is
 * alive" rather than as an audible effect. */
const PAD_LFO_HZ = 0.06;
const PAD_LFO_DEPTH_HZ = 700;

const PAD_DELAY_SECONDS = 0.52;

/** Left and right delay times deliberately unequal, so repeats never line up
 * into a single centred echo. */
const PAD_DELAY_SKEW = 1.37;
const PAD_DELAY_FEEDBACK = 0.42;
const PAD_DELAY_DAMPING_HZ = 1800;
const PAD_DELAY_WET = 0.4;
const PAD_REVERB_WET = 0.55;

