// ─── Shared helpers ──────────────────────────────────────────────────────────

/**
 * Build a looping AudioBuffer of noise. Near-pure (allocates a buffer via the
 * context; deterministic given the same seed).
 *
 * WHY A BUFFER AND NOT A WORKLET: a noise worklet would burn a whole audio
 * thread slot to do what a looping BufferSource does in C++. The loop is long
 * enough (NOISE_SECONDS) that the repetition is not perceptible as a pattern.
 *
 * PINK vs WHITE: white noise has equal energy per Hz and sounds hissy and
 * top-heavy; pink has equal energy per OCTAVE, which matches how hearing works
 * and is what actually sounds like wind, surf, or a room. Pink is generated by
 * the Voss-McCartney-style filter cascade below — the standard cheap
 * approximation of a -3 dB/octave slope.
 */
function createNoiseBuffer(context, color, seed) {
  const length = Math.floor(NOISE_SECONDS * context.sampleRate);
  const buffer = context.createBuffer(1, length, context.sampleRate);
  const data = buffer.getChannelData(0);

  // Seeded so a patch's noise bed is reproducible across reloads.
  let state = seed >>> 0 || 1;
  const nextRandom = () => {
    state ^= state << 13;
    state ^= state >>> 17;
    state ^= state << 5;
    return ((state >>> 0) / 4294967296) * 2 - 1;
  };

  if (color === "white") {
    for (let i = 0; i < length; i++) data[i] = nextRandom();
  } else {
    // Paul Kellet's pink-noise filter cascade: six one-pole filters summed,
    // approximating -3 dB/octave to within 0.05 dB across the audible band.
    let b0 = 0, b1 = 0, b2 = 0, b3 = 0, b4 = 0, b5 = 0, b6 = 0;
    for (let i = 0; i < length; i++) {
      const white = nextRandom();
      b0 = 0.99886 * b0 + white * 0.0555179;
      b1 = 0.99332 * b1 + white * 0.0750759;
      b2 = 0.969 * b2 + white * 0.153852;
      b3 = 0.8665 * b3 + white * 0.3104856;
      b4 = 0.55 * b4 + white * 0.5329522;
      b5 = -0.7616 * b5 - white * 0.016898;
      data[i] = (b0 + b1 + b2 + b3 + b4 + b5 + b6 + white * 0.5362) * PINK_GAIN_TRIM;
      b6 = white * 0.115926;
    }
  }
  return buffer;
}

/** Long enough that the loop point is not heard as a rhythm. */
const NOISE_SECONDS = 4;

/** The Kellet cascade sums to roughly 3x unity; trims back to ~±1. */
const PINK_GAIN_TRIM = 0.11;

/**
 * A constant-signal source: a DC offset of 1.0 that any gain can scale.
 *
 * This is the standard Web Audio idiom for "a number as a signal" — it is what
 * lets a knob value be WIRED into an AudioParam and summed with modulation,
 * which is the whole basis of the modular paradigm.
 */
function createConstant(context, value) {
  const constant = context.createConstantSource();
  constant.offset.value = value;
  return constant;
}

// ─── 1. Output ───────────────────────────────────────────────────────────────

/**
 * OUTPUT — the terminal module: master volume, a limiter, and the tap the
 * engine's master meter reads.
 *
 * THE LIMITER IS NOT OPTIONAL. A modular patch can trivially sum six oscillators
 * into clipping, and digital clipping is harsh and can be genuinely painful in
 * headphones. A DynamicsCompressor with a high ratio and a low threshold acts as
 * a safety limiter that is inaudible until something is too loud. Native, so it
 * costs nothing.
 */
function outputModule(context, params, resources) {
  const input = context.createGain();
  const volume = context.createGain();
  const limiter = context.createDynamicsCompressor();

  volume.gain.value = clampParam(params.volume ?? 0.7, 0, 1, "volume");
  limiter.threshold.value = LIMITER_THRESHOLD_DB;
  limiter.knee.value = LIMITER_KNEE_DB;
  limiter.ratio.value = LIMITER_RATIO;
  limiter.attack.value = LIMITER_ATTACK_SECONDS;
  limiter.release.value = LIMITER_RELEASE_SECONDS;

  input.connect(volume);
  volume.connect(limiter);
  // THE ENGINE'S MASTER BUS, NOT `context.destination` (R7-22). Every output
  // module lands on one node, which is what gives the session a single place to
  // mute and a single place to record. Required, never defaulted: an output wired
  // straight to the destination would be audible while the rest of the patch was
  // muted, and invisible to a recorder — a silent-but-plausible failure in both
  // directions, which is exactly the class this codebase refuses to paper over.
  if (!resources?.destination) {
    throw new Error("outputModule: resources.destination (the engine's master bus) is required — see the master-chain block in synth/engine.js");
  }
  limiter.connect(resources.destination);

  return {
    inputs: { in: input },
    outputs: {},
    params: { volume: volume.gain },
    tap: limiter,
    start() {},
    dispose() {
      input.disconnect();
      volume.disconnect();
      limiter.disconnect();
    },
    meta: { kind: "output", label: "Output" },
  };
}

const LIMITER_THRESHOLD_DB = -6;
const LIMITER_KNEE_DB = 3;
const LIMITER_RATIO = 12;
const LIMITER_ATTACK_SECONDS = 0.003;
const LIMITER_RELEASE_SECONDS = 0.25;

// ─── 2. Oscillator ───────────────────────────────────────────────────────────

/**
 * OSCILLATOR — sine/triangle/sawtooth/square with detune. Pure native
 * OscillatorNode, which is band-limited in C++ (so no aliasing, and no need for
 * the PolyBLEP the research describes for a hand-rolled one).
 *
 * `frequency` and `detune` are AudioParams, so they accept wires as well as
 * knob values — that is how an LFO or envelope modulates pitch.
 * `waveform` is DISCRETE (a setter, not an AudioParam): rampSeconds is
 * meaningless for it and is ignored.
 */
function oscillatorModule(context, params) {
  const oscillator = context.createOscillator();
  const output = context.createGain();

  oscillator.type = params.waveform ?? "sine";
  oscillator.frequency.value = clampParam(params.frequency ?? 220, MIN_AUDIBLE_HZ, MAX_AUDIBLE_HZ, "frequency");
  oscillator.detune.value = clampParam(params.detune ?? 0, -MAX_DETUNE_CENTS, MAX_DETUNE_CENTS, "detune");
  output.gain.value = clampParam(params.level ?? 0.5, 0, 1, "level");
  oscillator.connect(output);

  let started = false;
  return {
    inputs: { frequency: oscillator.frequency, detune: oscillator.detune, level: output.gain },
    outputs: { out: output },
    params: {
      frequency: oscillator.frequency,
      detune: oscillator.detune,
      level: output.gain,
      waveform: (value) => {
        oscillator.type = value;
      },
    },
    start() {
      if (started) return;
      oscillator.start();
      started = true;
    },
    dispose() {
      if (started) oscillator.stop();
      oscillator.disconnect();
      output.disconnect();
    },
    meta: { kind: "oscillator", label: "Oscillator" },
  };
}

/** ±2 octaves of detune range, in cents. Beyond that, use frequency. */
const MAX_DETUNE_CENTS = 2400;

// ─── 3. Supersaw ─────────────────────────────────────────────────────────────

/**
 * SUPERSAW — a stack of detuned sawtooth oscillators, the raw material of the
 * ambience pad and the classic "huge" synth sound.
 *
 * The detune fan comes from dsp.supersawDetunes (pure, tested). Each voice is a
 * native OscillatorNode; the per-voice gain is 1/sqrt(n) rather than 1/n
 * because the voices are UNCORRELATED, so their amplitudes add in RMS (as the
 * square root) rather than linearly. Using 1/n would make an 7-voice stack
 * noticeably quieter than a 1-voice one.
 */
function supersawModule(context, params) {
  const output = context.createGain();
  const voiceCount = Math.max(1, Math.floor(params.voices ?? 7));
  const baseFrequency = clampParam(params.frequency ?? 110, MIN_AUDIBLE_HZ, MAX_AUDIBLE_HZ, "frequency");
  const detunes = supersawDetunes(voiceCount, params.spread ?? 14);

  output.gain.value = clampParam(params.level ?? 0.4, 0, 1, "level");

  const oscillators = detunes.map((cents) => {
    const oscillator = context.createOscillator();
    const voiceGain = context.createGain();
    oscillator.type = "sawtooth";
    oscillator.frequency.value = baseFrequency;
    oscillator.detune.value = cents;
    voiceGain.gain.value = 1 / Math.sqrt(voiceCount);
    oscillator.connect(voiceGain);
    voiceGain.connect(output);
    return oscillator;
  });

  let started = false;
  return {
    inputs: { level: output.gain },
    outputs: { out: output },
    params: {
      level: output.gain,
      // Frequency fans out to every voice, each keeping its own detune.
      frequency: (value, when, ramp) => {
        const target = clampParam(value, MIN_AUDIBLE_HZ, MAX_AUDIBLE_HZ, "frequency");
        for (const oscillator of oscillators) {
          if (ramp > 0) oscillator.frequency.setTargetAtTime(target, when, ramp);
          else oscillator.frequency.setValueAtTime(target, when);
        }
      },
      spread: (value) => {
        const nextDetunes = supersawDetunes(voiceCount, value);
        oscillators.forEach((oscillator, i) => {
          oscillator.detune.value = nextDetunes[i];
        });
      },
    },
    start() {
      if (started) return;
      for (const oscillator of oscillators) oscillator.start();
      started = true;
    },
    dispose() {
      for (const oscillator of oscillators) {
        if (started) oscillator.stop();
        oscillator.disconnect();
      }
      output.disconnect();
    },
    meta: { kind: "supersaw", label: "Supersaw" },
  };
}

