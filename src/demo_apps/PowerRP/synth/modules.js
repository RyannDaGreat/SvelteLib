// ─── 17-18. Clock and sequencer ──────────────────────────────────────────────

/**
 * CLOCK — a BPM source. Emits a pulse train on its output AND drives the
 * engine's scheduler.
 *
 * The audible/wireable pulse is a native oscillator shaped into a pulse by a
 * WaveShaper; the SCHEDULING is done by the two-clock scheduler, not by this
 * signal. That split matters: a wire carries the clock to other MODULES, while
 * the scheduler carries it to EVENTS, and the latter has to be sample-accurate
 * in a way a signal path cannot express.
 */
function clockModule(context, params) {
  const oscillator = context.createOscillator();
  const shaper = context.createWaveShaper();
  const output = context.createGain();

  const bpm = clampParam(params.bpm ?? 90, 20, 300, "bpm");
  oscillator.type = "square";
  oscillator.frequency.value = (bpm / 60) * (params.stepsPerBeat ?? 4);
  // Map the square's -1..1 to a clean 0..1 gate: everything below 0 -> 0.
  shaper.curve = gateCurve();
  oscillator.connect(shaper);
  shaper.connect(output);

  let started = false;
  return {
    inputs: {},
    outputs: { out: output },
    params: { frequency: oscillator.frequency },
    start() {
      if (started) return;
      oscillator.start();
      started = true;
    },
    dispose() {
      if (started) oscillator.stop();
      oscillator.disconnect();
      shaper.disconnect();
      output.disconnect();
    },
    meta: { kind: "clock", label: "Clock", bpm },
  };
}

/** A 2-point curve mapping negatives to 0 and positives to 1 — the cheapest
 * bipolar-to-unipolar gate conversion, and it runs in C++. */
function gateCurve() {
  const curve = new Float32Array(GATE_CURVE_POINTS);
  for (let i = 0; i < GATE_CURVE_POINTS; i++) {
    curve[i] = i < GATE_CURVE_POINTS / 2 ? 0 : 1;
  }
  return curve;
}

const GATE_CURVE_POINTS = 256;

/**
 * SEQUENCER — 16 steps of pitch + gate, driven by the engine's scheduler.
 *
 * The module itself owns only the PATTERN and a control-signal output; the
 * timing comes from the shared scheduler, so every sequencer in a patch is
 * locked to one transport. Step events are delivered to the engine, which fires
 * them at their scheduled audio-clock time.
 */
function sequencerModule(context, params) {
  const pitchOutput = createConstant(context, 0);
  const gateOutput = context.createGain();
  const gateSource = createConstant(context, 0);
  gateSource.connect(gateOutput);

  const steps = normalizeSteps(params.steps, params.stepCount ?? DEFAULT_SEQUENCER_STEPS);

  let started = false;
  return {
    inputs: {},
    outputs: { pitch: pitchOutput, gate: gateOutput },
    params: {
      steps: (value) => {
        const next = normalizeSteps(value, steps.length);
        for (let i = 0; i < steps.length; i++) steps[i] = next[i];
      },
    },
    /**
     * Command. Play one step at an audio-clock time. Called by the engine from
     * the scheduler, never from a timer directly — that is what makes the
     * timing sample-accurate.
     */
    playStep(index, time) {
      const step = steps[index % steps.length];
      if (!step || !step.on) return;
      const hz = midiToFreq(step.note);
      pitchOutput.offset.setValueAtTime(hz, time);
      // AND AS A PLAIN NUMBER, for whoever is STRUCK by this step (WORKSTREAM CC).
      // A scheduled setValueAtTime does NOT move `offset.value` — measured — so a
      // module reading the param on the control thread sees the pitch it had
      // BEFORE this step, which for a patch whose pitch comes only from the wire
      // is the initial 0. That is why Gamelan Bells played its whole melody at the
      // 20 Hz clamp. `controlValue` is the same number, readable where a discrete
      // strike is decided; the AudioParam remains the thing an audio-rate consumer
      // is connected to, so the wire's audio-thread behaviour is unchanged.
      pitchOutput.controlValue = hz;
      // A short gate pulse: up at `time`, down a moment later. The receiving
      // ADSR's Schmitt detector sees a clean rising edge.
      gateSource.offset.setValueAtTime(1, time);
      gateSource.offset.setValueAtTime(0, time + SEQUENCER_GATE_SECONDS);
    },
    start() {
      if (started) return;
      pitchOutput.start();
      gateSource.start();
      started = true;
    },
    dispose() {
      if (started) {
        pitchOutput.stop();
        gateSource.stop();
      }
      pitchOutput.disconnect();
      gateSource.disconnect();
      gateOutput.disconnect();
    },
    meta: { kind: "sequencer", label: "Sequencer", stepCount: steps.length },
  };
}

/** Coerce a pattern into a full-length array of {on, note} — a short or sparse
 * pattern is padded with rests rather than throwing, because a partially
 * authored pattern is a normal editing state, not an error. */
function normalizeSteps(steps, count) {
  const normalized = [];
  for (let i = 0; i < count; i++) {
    const step = steps && steps[i];
    if (typeof step === "number") normalized.push({ on: true, note: step });
    else if (step && typeof step === "object") normalized.push({ on: step.on !== false, note: step.note ?? 60 });
    else normalized.push({ on: false, note: 60 });
  }
  return normalized;
}

const DEFAULT_SEQUENCER_STEPS = 16;

/** Long enough for a Schmitt detector to see a clean edge, short enough to read
 * as a trigger rather than a sustained gate. */
const SEQUENCER_GATE_SECONDS = 0.02;

// ─── 19. Sampler ─────────────────────────────────────────────────────────────

/**
 * SAMPLER / LOOPER — plays an AudioBuffer, optionally seamlessly looped.
 *
 * The buffer is supplied by the host (PowerRP will hand it a decoded asset);
 * the module never fetches, because a synth module doing network I/O would be
 * exactly the ephemeral state the architecture forbids.
 *
 * Loop points default to the whole buffer. The research's seamless-loop rule
 * (zero-crossing boundaries) is the ASSET's responsibility — we expose
 * loopStart/loopEnd so a caller can honor it.
 */
function samplerModule(context, params) {
  const output = context.createGain();
  output.gain.value = clampParam(params.level ?? 0.8, 0, 1, "level");

  let source = null;
  let started = false;
  const buffer = params.buffer ?? null;

  function build() {
    source = context.createBufferSource();
    source.buffer = buffer;
    source.loop = params.loop !== false;
    if (params.loopStart !== undefined) source.loopStart = params.loopStart;
    if (params.loopEnd !== undefined) source.loopEnd = params.loopEnd;
    source.playbackRate.value = clampParam(params.rate ?? 1, MIN_PLAYBACK_RATE, MAX_PLAYBACK_RATE, "rate");
    source.connect(output);
  }

  return {
    inputs: { level: output.gain },
    outputs: { out: output },
    params: {
      level: output.gain,
      rate: (value) => {
        if (source) source.playbackRate.value = clampParam(value, MIN_PLAYBACK_RATE, MAX_PLAYBACK_RATE, "rate");
      },
    },
    start() {
      if (started || !buffer) return;
      build();
      source.start();
      started = true;
    },
    dispose() {
      if (source) {
        if (started) source.stop();
        source.disconnect();
      }
      output.disconnect();
    },
    meta: { kind: "sampler", label: "Sampler" },
  };
}

const MIN_PLAYBACK_RATE = 0.05;
const MAX_PLAYBACK_RATE = 8;

